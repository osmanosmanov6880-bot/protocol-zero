test('WAVE 08: diagnostics show interval and SRM warning, never automatic winner',async()=>{
  const {createPlan}=require('../src/experiments');
  const ownerId=db.prepare('SELECT owner_session AS id FROM brand_submissions WHERE id=?').get(brief).id;
  const created=createPlan(db,[],ownerId,brief,{controlBranchId:root,treatmentBranchId:branch,metric:'lead',hypothesis:'Проверяем понятность рекламной идеи, не утверждаем победу.'});
  const zero=auditExperiment(db,ownerId,created.id);
  assert.equal(zero.arms.A.goalRate,null);assert.equal(zero.balance.checked,false);
  for(let i=0;i<120;i++)db.prepare('INSERT INTO experiment_assignments(experiment_id,platform_key,participant_hash,arm,impressed,converted) VALUES(?,?,?,?,?,?)').run(created.id,'test_fixture',String(i).padStart(64,'0'),i<100?'A':'B',1,i%7===0?1:0);
  const audit=auditExperiment(db,ownerId,created.id);
  assert.equal(audit.balance.warning,true);
  assert(audit.flags.some(x=>x.code==='SAMPLE_RATIO_MISMATCH'));
  assert.equal(audit.arms.A.goalRate.denominator,100);
  assert.equal(audit.arms.B.goalRate.denominator,20);
  assert.match(audit.decision,/Недостаточно оснований/);
  assert.equal((await stranger('/api/experiments/'+created.id+'/integrity')).status,403);
  assert.equal((await owner('/api/experiments/'+created.id+'/integrity')).status,200);
});
